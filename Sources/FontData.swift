func textToColumns(_ text: String, gap: Int = 1) -> [UInt8] {
    var cols: [UInt8] = []
    let upper = text.uppercased()
    for (i, ch) in upper.enumerated() {
        let charCols = FONT[ch] ?? FONT[" "]!
        if i > 0 {
            cols += [UInt8](repeating: BLANK_COL, count: gap)
        }
        cols += charCols
    }
    return cols
}
